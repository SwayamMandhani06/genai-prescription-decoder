def main():
    os.makedirs(REFERENCE_DIR, exist_ok=True)
    cdsco_records = build_cdsco_records()
    rxnorm_records = build_rxnorm_records()

    cdsco_path = os.path.join(REFERENCE_DIR, "cdsco_approved_drugs.json")
    rxnorm_path = os.path.join(REFERENCE_DIR, "nlm_rxnorm_drugs.json")

    with open(cdsco_path, "w", encoding="utf-8") as f:
        json.dump(cdsco_records, f, indent=2)

    with open(rxnorm_path, "w", encoding="utf-8") as f:
        json.dump(rxnorm_records, f, indent=2)

    # Compute cryptographic checksums
    with open(cdsco_path, "rb") as f:
        cdsco_sha256 = hashlib.sha256(f.read()).hexdigest()
    with open(rxnorm_path, "rb") as f:
        rxnorm_sha256 = hashlib.sha256(f.read()).hexdigest()

    manifest = {
        "manifest_version": "1.0.0",
        "created_at": "2026-09-27T00:00:00Z",
        "reference_sources": [
            {
                "source_id": "cdsco-approved-drugs",
                "file_path": "data/reference/cdsco_approved_drugs.json",
                "record_count": len(cdsco_records),
                "sha256": cdsco_sha256,
                "provenance": CDSCO_PROVENANCE,
            },
            {
                "source_id": "nlm-rxnorm",
                "file_path": "data/reference/nlm_rxnorm_drugs.json",
                "record_count": len(rxnorm_records),
                "sha256": rxnorm_sha256,
                "provenance": RXNORM_PROVENANCE,
            }
        ],
        "summary": {
            "total_records": len(cdsco_records) + len(rxnorm_records),
            "sources_cataloged": 2,
            "verification_status": "verified_regulatory",
        }
    }

    manifest_path = os.path.join(REFERENCE_DIR, "reference_manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print(f"Reference datasets successfully built:")
    print(f"  CDSCO records:  {len(cdsco_records)} ({cdsco_sha256[:12]}...)")
    print(f"  RxNorm records: {len(rxnorm_records)} ({rxnorm_sha256[:12]}...)")
    print(f"  Manifest written to: {manifest_path}")


if __name__ == "__main__":
    main()
